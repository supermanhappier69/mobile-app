#!/usr/bin/env node
// Copies packages/core/src into supabase/functions/_shared/core with Deno-compatible imports
// (explicit .ts extensions, npm: specifier for zod). `--check` fails if the copy is stale (CI).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/core/src');
const dest = join(root, 'supabase/functions/_shared/core');
const check = process.argv.includes('--check');

const zodVersion = JSON.parse(readFileSync(join(root, 'node_modules/zod/package.json'), 'utf8')).version;
const HEADER = '// GENERATED by scripts/sync-core.mjs from packages/core/src — edit the source, then run `npm run core:sync`.\n';

function listTs(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === '__tests__' ? [] : listTs(full);
    return entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts') ? [full] : [];
  });
}

function transform(code) {
  return (
    HEADER +
    code
      .replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)(['"])/g, (match, open, path, close) =>
        path.endsWith('.ts') ? match : `${open}${path}.ts${close}`,
      )
      .replace(/(from\s+['"])zod(['"])/g, `$1npm:zod@${zodVersion}$2`)
  );
}

const expected = new Map(listTs(src).map((file) => [relative(src, file), transform(readFileSync(file, 'utf8'))]));
const existing = existsSync(dest) ? listTs(dest).map((file) => relative(dest, file)) : [];

if (check) {
  const problems = [];
  for (const [file, content] of expected) {
    const target = join(dest, file);
    if (!existsSync(target)) problems.push(`missing ${file}`);
    else if (readFileSync(target, 'utf8') !== content) problems.push(`stale ${file}`);
  }
  for (const file of existing) if (!expected.has(file)) problems.push(`extra ${file}`);
  if (problems.length) {
    console.error(`supabase/functions/_shared/core is out of date (run npm run core:sync):\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`core copy up to date (${expected.size} files)`);
} else {
  rmSync(dest, { recursive: true, force: true });
  for (const [file, content] of expected) {
    const target = join(dest, file);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`synced ${expected.size} core files → ${relative(root, dest)}`);
}
